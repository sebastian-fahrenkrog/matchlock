package net

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func writeResolvConf(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "resolv.conf")
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
	return path
}

func TestResolvConfUpstreams_PlainNameservers(t *testing.T) {
	path := writeResolvConf(t, "nameserver 10.0.2.3\nnameserver 1.1.1.1\noptions ndots:0\n")
	assert.Equal(t, []string{"10.0.2.3", "1.1.1.1"}, ResolvConfUpstreams(path))
}

func TestResolvConfUpstreams_EmbeddedWithExternal(t *testing.T) {
	// Docker's file for a container on a user-defined network under rootless
	// docker with slirp4netns (27 Oct 2026).
	path := writeResolvConf(t, `# Generated by Docker Engine.
nameserver 127.0.0.11
options ndots:0

# Based on host file: '/etc/resolv.conf' (internal resolver)
# ExtServers: [10.0.2.3]
# Overrides: []
`)
	assert.Equal(t, []string{"10.0.2.3"}, ResolvConfUpstreams(path))
}

func TestResolvConfUpstreams_EmbeddedWithHostLoopbackOnly(t *testing.T) {
	// Rootful docker on a systemd-resolved host: the embedded resolver reaches
	// 127.0.0.53 from the host's namespace, so it stays the upstream.
	path := writeResolvConf(t, "nameserver 127.0.0.11\n# ExtServers: [host(127.0.0.53)]\n")
	assert.Equal(t, []string{"127.0.0.11"}, ResolvConfUpstreams(path))
}

func TestResolvConfUpstreams_MixedExternal(t *testing.T) {
	path := writeResolvConf(t, "nameserver 127.0.0.11\n# ExtServers: [host(127.0.0.53) 10.0.2.3 9.9.9.9]\n")
	assert.Equal(t, []string{"10.0.2.3", "9.9.9.9"}, ResolvConfUpstreams(path))
}

func TestResolvConfUpstreams_EmbeddedWithoutExternal(t *testing.T) {
	path := writeResolvConf(t, "nameserver 127.0.0.11\n")
	assert.Equal(t, []string{"127.0.0.11"}, ResolvConfUpstreams(path))
}

func TestResolvConfUpstreams_EmptyOrMissing(t *testing.T) {
	assert.Nil(t, ResolvConfUpstreams(writeResolvConf(t, "options ndots:0\n")))
	assert.Nil(t, ResolvConfUpstreams(filepath.Join(t.TempDir(), "nope")))
}
